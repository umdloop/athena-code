            cv2.imwrite(out_ip, cv2.cvtColor(img2, cv2.COLOR_RGB2BGR))
            out_lp = os.path.join(split_out,'labels', f"{base}_aug{k}.txt")
            write_yolo_labels(out_lp, b2, c2)

