        base,ext = os.path.splitext(os.path.basename(ip))
        lp = os.path.join(split_src,'labels', base+'.txt')
        img = cv2.cvtColor(cv2.imread(ip), cv2.COLOR_BGR2RGB)
        boxes, classes = read_yolo_labels(lp)

        # NEW: sanitize input boxes BEFORE calling aug (this fixes your error)
        boxes, classes = sanitize_boxes(boxes, classes)

        # copy originals (optional to also write sanitized original labels)
        shutil.copy2(ip, os.path.join(split_out,'images', base+ext))
        if os.path.exists(lp):
            write_yolo_labels(os.path.join(split_out,'labels', base+'.txt'), boxes, classes)

        for k in range(n_aug):
            if boxes:
                t = aug(image=img, bboxes=boxes, class_labels=classes)
                img2, b2_raw, c2_raw = t['image'], t['bboxes'], t['class_labels']

