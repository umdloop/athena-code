# 3) Pairing & class-ID scan
IMG_EXT = (".jpg",".jpeg",".png",".bmp",".tif",".tiff",".webp")
def list_imgs(d: Path):
    return [p for p in Path(d).glob("*") if p.suffix.lower() in IMG_EXT]

def label_for(img: Path, lbl_dir: Path):
    return Path(lbl_dir) / (img.stem + ".txt")

def pairing_report(img_dir, lbl_dir, name):
    imgs = list_imgs(img_dir)
    miss = [p.name for p in imgs if not label_for(p, lbl_dir).exists()]
    print(f"{name}: {len(imgs)} images; {len(miss)} missing labels")
    if miss[:5]:
        print("  sample missing:", miss[:5])

def scan_ids(lbl_dir, max_id):
    bad = []
    for p in sorted(Path(lbl_dir).glob("*.txt")):
        try:
            arr = np.loadtxt(p, ndmin=2)
            if arr.size == 0:
                continue
            cls = arr[:,0].astype(int)
            if (cls < 0).any() or (cls > max_id).any():
                bad.append(p.name)
        except Exception:
            bad.append(p.name)
    if bad:
        print(f"[WARN] {len(bad)} label files have class IDs outside 0..{max_id}. e.g.:", bad[:5])
    else:
        print(f"Class IDs OK (0..{max_id}).")

if ok_all:
    print("\n--- DATASET SANITY ---")
    pairing_report(train_img, train_lbl, "train")
    pairing_report(val_img,   val_lbl,   "val")
    if test_img and test_lbl:
        pairing_report(test_img, test_lbl, "test")
    scan_ids(train_lbl, len(names)-1)
    scan_ids(val_lbl,   len(names)-1)

