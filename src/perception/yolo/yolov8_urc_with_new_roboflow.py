def yolo_line_to_row(img_path: Path, img_size, names_map, parts):
    # parts: class xc yc w h [conf]
    has_conf = len(parts) == 6
    cls = int(float(parts[0]))
    xc, yc, w, h = map(float, parts[1:5])
    W, H = img_size
    # normalized -> pixel corners
    x1 = (xc - w/2) * W
    y1 = (yc - h/2) * H
    x2 = (xc + w/2) * W
    y2 = (yc + h/2) * H
    return {
        "image": str(img_path),
        "class_id": cls,
        "class_name": names_map.get(cls, str(cls)),
        "conf": float(parts[5]) if has_conf else None,
        "x1": x1, "y1": y1, "x2": x2, "y2": y2,
        "w_px": x2-x1, "h_px": y2-y1,
        "w_norm": w, "h_norm": h,
        "img_w": W, "img_h": H
    }

rows = []
