# --- clamp helpers (prevents tiny negatives like -7.8e-06) ---
def _clip01(v):
    return 0.0 if v < 0.0 else (1.0 if v > 1.0 else v)

def clip_yolo_box(box_xywh):
    # box in YOLO [x_center, y_center, w, h] (normalized)
    x, y, w, h = box_xywh
    x1 = _clip01(x - w/2.0); y1 = _clip01(y - h/2.0)
    x2 = _clip01(x + w/2.0); y2 = _clip01(y + h/2.0)
    if x2 <= x1 or y2 <= y1:
        return None
    cx = (x1 + x2) / 2.0; cy = (y1 + y2) / 2.0
    w2 = x2 - x1; h2 = y2 - y1
    return [cx, cy, w2, h2]

def sanitize_boxes(boxes, classes):
    """Clamp all boxes to [0,1] and drop degenerate/tiny ones."""
    out_b, out_c = [], []
    for b,c in zip(boxes, classes):
        bb = clip_yolo_box(b)
        if bb is not None and (bb[2]*bb[3]) > 1e-8:
            out_b.append(bb); out_c.append(c)
    return out_b, out_c

